import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
const id='tv-profile-tenth-doctor',file='David Tennant - Los Angeles Comic Con 2025.jpg',name=file.replaceAll(' ','_');
const hash=createHash('md5').update(name).digest('hex');
const url=`https://thumb.wikimedia.org/wikipedia/commons/thumb/${hash[0]}/${hash.slice(0,2)}/${encodeURIComponent(name)}/960px-${encodeURIComponent(name)}`;
const response=await fetch(url,{headers:{'User-Agent':'FandomVerseCompetition/1.0 (educational CC media audit)'}});
if(!response.ok)throw Error(`HTTP ${response.status}`);
const bytes=Buffer.from(await response.arrayBuffer());
for(const width of [480,960])for(const format of ['webp','avif'])await sharp(bytes).rotate().resize({width,withoutEnlargement:true})[format]({quality:format==='avif'?49:76}).toFile(`public/media/${id}-${width}.${format}`);
const sourceUrl=`https://commons.wikimedia.org/wiki/File:${encodeURIComponent(name)}`;
const register=JSON.parse(await fs.readFile('docs/assets-profile-expansion.json','utf8'));
const index=register.findIndex(x=>x.id===id);
register[index]={id,file,creator:'Kevin Paul',license:'CC BY 4.0',alt:'David Tennant, who portrays the Tenth Doctor, at Los Angeles Comic Con 2025',files:`${id}-{480,960}.{webp,avif}`,sourceUrl,originalUrl:url,permissionBasis:'Creative Commons license on Commons file page',changes:'Resized and converted to WebP and AVIF',verifiedAt:'2026-09-26',originalBytes:bytes.length};
await fs.writeFile('docs/assets-profile-expansion.json',JSON.stringify(register,null,2)+'\n');
const path='src/data/tv.json',rows=JSON.parse(await fs.readFile(path,'utf8'));
const row=rows.find(x=>x.id===id);
Object.assign(row,{imageAlt:register[index].alt,imageCredit:'Kevin Paul · CC BY 4.0',imageKind:'performer-photo',imageSourceUrl:sourceUrl,mediaPermission:'CC BY 4.0 performer photograph; shows David Tennant, not an official Doctor Who still.'});
await fs.writeFile(path,JSON.stringify(rows,null,2)+'\n');
